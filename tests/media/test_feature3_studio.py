"""Feature 3 offline CPU and provider contract regression tests.

Assets are synthetic local fixtures, not AI model inference or licensed media.
"""
import importlib.util
import shutil
import sys
import tempfile
import unittest
from pathlib import Path
from uuid import uuid4

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "poster-engine"))
from studio_v2 import (SCHEMA, DesignError, compose_poster,
                       render_design, validate_design)
from animate_v2 import export_animation
from gpu_worker_v2 import OfflineFluxKlein4B, ReviewedTryOn, ReviewedBackgroundRemoval
from ai_providers_v2 import (OptionalGPUProvider, ProviderBlocked,
                             FLUX_KLEIN_4B, FASHN_VTON_15, InferenceJob,
                             ProviderConfig)


class Feature3Tests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.shop = str(uuid4())
        self.asset = str(uuid4())
        Image.new("RGB", (160, 220), "#C37E65").save(self.root / "cloth.png")
        self.manifest = {
            "shop_id": self.shop,
            "assets": {
                self.asset: {
                    "shop_id": self.shop, "kind": "image", "path": "cloth.png",
                    "rights": {
                        "license": "owned", "commercial_use": True,
                        "source": "synthetic_test_fixture",
                        "evidence": "generated by local Pillow tests",
                    },
                },
            },
        }

    def design(self, **kw):
        return compose_poster(shop_id=self.shop, mode="image",
                              prompt="Premium Diwali clothing", business_name="Test Boutique",
                              source_asset_id=self.asset, **kw)

    def test_text_to_poster_without_gpu_or_fabricated_offer(self):
        doc = compose_poster(shop_id=self.shop, mode="text",
                             prompt="20% OFF festive Diwali sale",
                             business_name="Clothing Shop")
        self.assertEqual(doc["schema"], SCHEMA)
        self.assertEqual(doc["template"], "festival")
        self.assertFalse(any(layer["id"] == "offer" for layer in doc["layers"]))
        result = render_design(doc, {"shop_id": self.shop, "assets": {}},
                               self.root, self.root / "text.png", scale=.25)
        with Image.open(result["path"]) as png:
            self.assertEqual(png.size, (270, 270))

    def test_image_to_poster_with_exact_authorized_offer(self):
        doc = self.design(headline="Diwali collection", approved_offer="20% OFF",
                          format="portrait")
        result = render_design(doc, self.manifest, self.root,
                               self.root / "image.png", scale=.25)
        with Image.open(result["path"]) as png:
            self.assertEqual(png.size, (270, 338))
        self.assertEqual(next(x for x in doc["layers"] if x["id"] == "offer")["text"],
                         "20% OFF")

    def test_templates_and_story_format(self):
        for template in ("fashion", "luxury", "streetwear", "ethnic", "festival",
                         "restaurant", "general", "new_arrivals", "clearance", "seasonal"):
            with self.subTest(template=template):
                doc = self.design(template=template, format="story")
                self.assertEqual(validate_design(doc)["format"], "story")

    def test_cross_tenant_revocation_and_unsafe_media(self):
        doc = self.design()
        other = dict(self.manifest, shop_id=str(uuid4()))
        with self.assertRaisesRegex(DesignError, "Cross-tenant"):
            render_design(doc, other, self.root, self.root / "bad.png")
        self.manifest["assets"][self.asset]["rights"]["commercial_use"] = False
        with self.assertRaisesRegex(DesignError, "rights"):
            render_design(doc, self.manifest, self.root, self.root / "bad.png")
        self.manifest["assets"][self.asset]["rights"]["commercial_use"] = True
        self.manifest["assets"][self.asset]["path"] = "https://evil.example/photo.jpg"
        with self.assertRaisesRegex(DesignError, "relative"):
            render_design(doc, self.manifest, self.root, self.root / "bad.png")

    def test_invalid_design_and_unknown_keys_rejected(self):
        doc = self.design()
        with self.assertRaisesRegex(DesignError, "Invalid versioned"):
            validate_design({**doc, "remote_image_url": "https://evil.example"})
        with self.assertRaisesRegex(DesignError, "Duplicate"):
            validate_design({**doc, "layers": [doc["layers"][0]] * 2})
        bad = [dict(x) for x in doc["layers"]]
        bad[0]["x"] = 1.2
        with self.assertRaisesRegex(DesignError, "coordinate"):
            validate_design({**doc, "layers": bad})
        bad = [dict(x) for x in doc["layers"]]
        next(layer for layer in bad if layer["type"] == "image")["asset_id"] = "../another-shop.png"
        with self.assertRaisesRegex(DesignError, "asset"):
            validate_design({**doc, "layers": bad})

    def test_gif_animation(self):
        doc = self.design(approved_offer="20% OFF")
        info = export_animation(doc, self.manifest, self.root, self.root / "offer.gif",
                                fps=3, duration=1, scale=.2)
        self.assertFalse(info["inference"])
        with Image.open(info["path"]) as gif:
            self.assertEqual(gif.format, "GIF")
            self.assertEqual(gif.n_frames, 3)

    @unittest.skipUnless(shutil.which("ffmpeg"), "ffmpeg missing on local runner")
    def test_mp4_animation(self):
        doc = self.design(approved_offer="20% OFF")
        info = export_animation(doc, self.manifest, self.root, self.root / "offer.mp4",
                                fps=3, duration=1, scale=.2)
        self.assertEqual(info["format"], "mp4")
        self.assertGreater((self.root / "offer.mp4").stat().st_size, 200)

    def test_provider_contract_license_cost_and_tenant_gates(self):
        provider = OptionalGPUProvider(FLUX_KLEIN_4B)
        job = InferenceJob(shop_id=self.shop, job_id=str(uuid4()),
                           capability="human_model", prompt="Adult fashion studio portrait")
        self.assertFalse(provider.status()["enabled"])
        with self.assertRaises(ProviderBlocked):
            provider.execute(job, resolve_assets=lambda *_: {}, write_private_output=lambda *_: None)
        self.assertFalse(OptionalGPUProvider(FASHN_VTON_15).status()["licensed"])
        try_on = InferenceJob(shop_id=self.shop, job_id=str(uuid4()), capability="virtual_try_on",
                              source_asset_ids=(str(uuid4()), str(uuid4())), category="tops")
        try_on.validate(FASHN_VTON_15)
        with self.assertRaises(ValueError):
            InferenceJob(shop_id=self.shop, job_id=str(uuid4()), capability="virtual_try_on",
                         source_asset_ids=(), category="tops").validate(FASHN_VTON_15)
        with self.assertRaises(ProviderBlocked):
            InferenceJob(shop_id=self.shop, job_id=str(uuid4()), capability="human_model",
                         prompt="underage model").validate(FLUX_KLEIN_4B)

    @unittest.skipUnless(shutil.which("ffmpeg"), "ffmpeg missing on local runner")
    def test_synthetic_sample_posters_and_animation_artifacts(self):
        # Media CI already runs unittest discovery and uploads ci-artifacts/.
        # Produce inspectable CI evidence without any customer data or AI.
        from sample_feature3 import samples
        outputs = samples(ROOT / "ci-artifacts" / "feature3")
        self.assertEqual(len(outputs), 4)
        for path in outputs:
            self.assertTrue(path.is_file())
            self.assertGreater(path.stat().st_size, 200)
        with Image.open(outputs[0]) as image:
            self.assertEqual(image.size, (1080, 1080))
        with Image.open(outputs[1]) as image:
            self.assertEqual(image.size, (1080, 1350))
        with Image.open(outputs[2]) as gif:
            self.assertEqual(gif.format, "GIF")
            self.assertGreaterEqual(gif.n_frames, 2)

    def test_gpu_disabled_without_local_weights_or_licensed_parser(self):
        with self.assertRaises(ProviderBlocked):
            OfflineFluxKlein4B(self.root / "missing-gpu-weights")
        with self.assertRaises(ProviderBlocked):
            ReviewedTryOn(lambda: None, parser_approval={"commercial_use_approved": False})
        with self.assertRaises(ProviderBlocked):
            ReviewedBackgroundRemoval(lambda image: image, model_provenance={
                "model_name": "BRIA-default", "commercial_use_approved": False,
                "weight_sha256": "not-licensed",
            })

    def test_reviewed_background_is_not_default_rembg_download(self):
        from io import BytesIO
        from PIL import Image
        adapter = ReviewedBackgroundRemoval(
            lambda image: image.convert("RGBA"),
            model_provenance={"commercial_use_approved": True,
                              "model_name": "injected_fixture", "weight_sha256": "fixture-hash"},
        )
        original = (self.root / "cloth.png").read_bytes()
        result = adapter(InferenceJob(self.shop, str(uuid4()), "background_remove",
                                      (self.asset,)), {self.asset: original})
        with Image.open(BytesIO(result)) as png:
            self.assertEqual(png.mode, "RGBA")

    def test_fake_runner_does_not_bypass_tenant_scoping(self):
        cfg = ProviderConfig("fixture", "test-1", frozenset({"image_edit"}),
                             "Apache-2.0", "Apache-2.0",
                             dependency_licenses_approved=True,
                             cost_approved=True, gpu_deployed=True)
        fixture = OptionalGPUProvider(cfg, runner=lambda job, files: b"SYNTHETIC_BYTES")
        job = InferenceJob(self.shop, str(uuid4()), "image_edit", (self.asset,))
        with self.assertRaises(ProviderBlocked):
            fixture.execute(job, resolve_assets=lambda *_: {},
                            write_private_output=lambda *_: None)
        observed = {}
        def writer(shop, job_id, payload, metadata):
            observed.update(metadata)
            self.assertEqual(shop, self.shop)
            self.assertEqual(payload, b"SYNTHETIC_BYTES")
            return "private-fixture-only"
        self.assertEqual(fixture.execute(job,
            resolve_assets=lambda shop, ids: {self.asset: b"SYNTHETIC_SOURCE"},
            write_private_output=writer), "private-fixture-only")
        self.assertTrue(observed["synthetic"])
        # This injection simulates the worker contract, NOT actual model inference.


if __name__ == "__main__":
    unittest.main()
