"""Feature3 Task3.2: signed tenant source-asset metadata only; no GPU."""
from pathlib import Path
import sys
import unittest
from uuid import uuid4

sys.path.insert(0,str(Path(__file__).resolve().parents[2]/"azure-functions/campaign-api"))
from feature3_v2_api import Feature3V2API
from tenant_store import TenantStore

S, A, U = [str(uuid4()) for _ in range(3)]
ROW={"id":A,"shop_id":S,"storage_bucket":"retailgrowth-media",
     "object_path":f"{S}/uploads/{A}.png", "mime_type":"image/png",
     "source":"UPLOAD","license_name":"owned",
     "license_url":None,"attribution":"Synthetic test garment generated by owner"}

class FakeTenant:
    def __init__(self, *, member=True, receipt=None):
        self.allow=member
        self.receipt={"mime_type":"image/png","license_name":"owned"} if receipt is None else receipt
        self.calls=0
    def member(self, token, user_id, shop_id, *, write=False):
        self.calls+=1
        assert write is True
        assert shop_id==S
        return self.allow
    def feature3_source_asset(self,token,shop_id,asset_id):
        return self.receipt

class SourceTests(unittest.TestCase):
    def test_actual_owner_metadata_is_not_approval_or_binary(self):
        api=Feature3V2API(FakeTenant(),None)
        code,payload=api.source_asset("jwt",U,S,A)
        self.assertEqual(code,200)
        self.assertEqual(payload["media_asset_id"],A)
        self.assertFalse(payload["private_bytes_verified"])
        self.assertFalse(payload["model_reviewed"])
        self.assertFalse(payload["gpu_eligible"])
        self.assertNotIn("object_path",payload)
        self.assertNotIn("url",payload)
    def test_foreign_and_viewer_fail_before_source_lookup(self):
        denied=FakeTenant(member=False)
        code,payload=Feature3V2API(denied,None).source_asset("jwt",U,S,A)
        self.assertEqual(code,404)
        self.assertEqual(payload,{"error":"NOT_FOUND"})
        self.assertEqual(denied.calls,1)
    def test_absent_private_source_is_not_model_ready(self):
        t=FakeTenant(receipt={})
        # Untrusted store responses must fail closed, not throw 500 or
        # falsely mark an empty source as registered.
        t.receipt=None
        self.assertEqual(Feature3V2API(t,None).source_asset("jwt",U,S,A)[0],404)
    def test_exact_tenant_private_registration_and_license(self):
        t=object.__new__(TenantStore)
        t._request=lambda *args,**kwargs:[dict(ROW)]
        self.assertEqual(t.feature3_source_asset("jwt",S,A)["mime_type"],"image/png")
        for change in [
            {"shop_id":str(uuid4())},
            {"object_path":f"{S}/uploads/other.png"},
            {"storage_bucket":"public"},
            {"source":"AI"},
            {"mime_type":"image/svg+xml"},
            {"license_name":"unknown"},
            {"attribution":""},
        ]:
            t._request=lambda *args,change=change,**kwargs:[{**ROW,**change}]
            self.assertIsNone(t.feature3_source_asset("jwt",S,A))
        t._request=lambda *args,**kwargs:[{**ROW,"license_name":"commercial",
                                                "license_url":"http://invalid"}]
        self.assertIsNone(t.feature3_source_asset("jwt",S,A))
        t._request=lambda *args,**kwargs:[{**ROW,"license_name":"commercial",
                                                "license_url":"https://licenses.example.org/img"}]
        self.assertIsNotNone(t.feature3_source_asset("jwt",S,A))

if __name__=="__main__":unittest.main()
