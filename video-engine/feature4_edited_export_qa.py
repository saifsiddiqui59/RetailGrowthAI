#!/usr/bin/env python3
"""Encoded 30s MOCK ONLY editor parity; never a retailer/AI quality approval.

Bounded CPU fixture with exact, frozen JS split/reorder edit layout:
source-video, product-photo, trimmed source-video, offer-poster scene.
Full video decoding (not HTML or mock proof) guards gross scene reorder,
second-video inpoint replay, missing video clip and missing distinct images.
Additional near-cut interior probes reject scene-family delays, but do NOT
certify exact transition frames, trim inpoints or commercial visual quality.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

from feature4_private_preview import inspect_mp4, PreviewExportError


class EditorExportProofError(ValueError):
    pass


def _sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as data:
        for block in iter(lambda: data.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def _frame(path, at):
    try:
        data = subprocess.run([
            "ffmpeg", "-nostdin", "-v", "error", "-protocol_whitelist", "file",
            "-ss", str(at), "-i", str(path), "-map", "0:v:0",
            "-vf", "scale=72:128,format=gray", "-frames:v", "1",
            "-f", "rawvideo", "-"
        ], capture_output=True, check=True, timeout=35).stdout
    except (OSError, subprocess.SubprocessError) as exc:
        raise EditorExportProofError("Cannot decode original edited MP4 frame") from exc
    if len(data) != 72 * 128:
        raise EditorExportProofError("Truncated encoded editor frame")
    return data


def _luma_delta(a, b):
    return sum(abs(x-y) for x, y in zip(a, b)) / len(a)


def verify_mock_editor_output(source: Path):
    """Audit actual encoded 540p 30s TEST edit scene families; never human art QA."""
    source = Path(source)
    try:
        metadata = inspect_mp4(source, max_size=80*1024*1024)
    except PreviewExportError as exc:
        raise EditorExportProofError("Expected encoded private H264/AAC input") from exc
    if ((metadata["width"], metadata["height"]) != (540, 960)
            or abs(metadata["seconds"] - 30) > .45):
        raise EditorExportProofError("Expected verified 30s 540p editor export")
    source_digest = _sha(source)
    # Source storyboard generated by actual Timeline Studio JS editor:
    # video 0..4, photo 4..14, trimmed same video 14..20,
    # different product/offer photo 20..30. Interior-only samples.
    at = (2.0, 7.0, 16.0, 24.0)
    first_video, first_photo, trimmed_video, offer_photo = [
        _frame(source, time) for time in at
    ]
    # Probe within each segment on BOTH sides of the edited cuts, not just
    # one frame per scene. One-second margins avoid confusing a legitimate
    # fade/transition with a missing or delayed clip. This proves only broad
    # scene-family parity, not frame-accurate trim or transition semantics.
    boundary_at = (5.0, 13.0, 15.0, 21.0)
    early_photo, late_photo, early_trimmed_video, early_offer = [
        _frame(source, time) for time in boundary_at
    ]
    if _sha(source) != source_digest:
        raise EditorExportProofError("Encoded MP4 changed during export QA sampling")
    video_pair = _luma_delta(first_video, trimmed_video)
    photo_pair = _luma_delta(first_photo, offer_photo)
    cross = min(
        _luma_delta(first_video, first_photo),
        _luma_delta(first_video, offer_photo),
        _luma_delta(trimmed_video, first_photo),
        _luma_delta(trimmed_video, offer_photo),
    )
    # Calibrated to this deliberate *original synthetic fixture* only.
    # The two video segments share footage, but the second is nonidentical
    # due to its reviewed 4s media in-point, not an exact identical replay.
    # Both product-photo scenes must remain distinct from each other and video.
    boundary_photo_delta = max(_luma_delta(early_photo, first_photo),
                               _luma_delta(late_photo, first_photo))
    boundary_offer_delta = _luma_delta(early_offer, offer_photo)
    boundary_video_separation = min(
        _luma_delta(early_trimmed_video, first_photo),
        _luma_delta(early_trimmed_video, offer_photo),
    )
    if not (2.0 < video_pair < .65 * cross and
            photo_pair >= 10.0 and cross >= 12.0 and
            boundary_photo_delta < .65 * photo_pair and
            boundary_offer_delta < .65 * photo_pair and
            boundary_video_separation >= .65 * cross):
        raise EditorExportProofError(
            "Actual encoded editor order/inpoint or image distinction regressed")
    return {
        "schema": "feature4_edited_30s_pixel_parity_v1",
        "status": "ENCODED_MOCK_EDITOR_ORDER_TECHNICALLY_VERIFIED",
        "source_sha256": source_digest,
        "profile": "30s/540x960/H264/AAC",
        "timeline_starts_seconds": [0, 4, 14, 20],
        "pixel_times_seconds": list(at),
        "boundary_probe_times_seconds": list(boundary_at),
        "boundary_photo_max_delta": round(boundary_photo_delta, 3),
        "boundary_offer_delta": round(boundary_offer_delta, 3),
        "boundary_video_min_separation": round(boundary_video_separation, 3),
        "boundary_scene_family_verified": True,
        "exact_transition_frame_verified": False,
        "repeated_source_video_delta": round(video_pair, 3),
        "different_photo_scene_delta": round(photo_pair, 3),
        "minimum_video_vs_photo_delta": round(cross, 3),
        "exact_inpoint_frame_verified": False,
        "human_visual_approval": False,
        "stock_model_product_match_verified": False,
        "commercial_release_eligible": False,
    }


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--source", required=True)
    cli.add_argument("--report", required=True)
    args = cli.parse_args()
    report = Path(args.report)
    if (report.is_symlink() or report.exists() or report.suffix.lower() != ".json"
            or not report.parent.is_dir() or report.parent.is_symlink()):
        raise EditorExportProofError("Private QA output must be new JSON")
    evidence = verify_mock_editor_output(Path(args.source))
    with report.open("x", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2)
        f.write("\n")
    print(json.dumps({"status": evidence["status"], "release_eligible": False}))


if __name__ == "__main__":
    main()
